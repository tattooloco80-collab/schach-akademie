import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push('PAGEERR ' + e.message)); page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) errs.push(m.type() + ' ' + m.text()); });
await page.goto('file:///home/claude/chess/dist/index.html'); await page.waitForTimeout(500);
await page.screenshot({ path: 'shots/01-home.png' });
await page.click('[data-a=play]'); await page.waitForTimeout(200);
await page.screenshot({ path: 'shots/02-setup.png' });
await page.fill('input[type=range]', '2'); await page.dispatchEvent('input[type=range]', 'input');
await page.click('.go'); await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/03-game.png' });
const sq = async (s) => { const b = await page.locator(`.sq[data-sq=${s}]`).boundingBox(); return [b.x + b.width / 2, b.y + b.height / 2]; };
const tap = async (s) => { const [x, y] = await sq(s); await page.touchscreen.tap(x, y); };
await tap('e2'); await page.waitForTimeout(150); await page.screenshot({ path: 'shots/04-select.png' });
await tap('e4'); await page.waitForTimeout(700); await page.screenshot({ path: 'shots/05-anim3d.png' });
console.log('3D overlay on?', await page.evaluate(() => !!document.querySelector('.o3d.on')), 'canvas', await page.evaluate(() => !!document.querySelector('.c3d')));
await page.waitForTimeout(6000); await page.screenshot({ path: 'shots/06-after.png' });
console.log('status:', await page.textContent('.status'), '| moves:', await page.textContent('.mlist'));
console.log('ERRORS', JSON.stringify(errs, null, 1));
await browser.close();
