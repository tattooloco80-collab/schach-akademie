import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const errs = [];
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage(); page.on('pageerror', (e) => errs.push('PAGEERR ' + e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
await page.goto('file:///home/claude/chess/dist/index.html'); await page.waitForTimeout(300);
await page.evaluate(() => { const a = window.__app; a.settings.anim = 'off'; a.settings.coachVoice = false; a.gameScreen({ mode: 'bot', level: 2, human: 'w', moves: [], tc: { min: 5, inc: 3 } }); });
await page.waitForTimeout(300);
const tap = async (s) => { const b = await page.locator(`.sq[data-sq=${s}]`).boundingBox(); await page.touchscreen.tap(b.x + b.width / 2, b.y + b.height / 2); await page.waitForTimeout(150); };
await tap('e2'); await tap('e4'); await page.waitForTimeout(2500);
console.log('Coach:', await page.textContent('.coach'));
console.log('Uhr:', await page.locator('.clk').allTextContents());
await page.screenshot({ path: 'shots/30-game.png' });
await tap('g1'); await tap('f3'); await page.waitForTimeout(2500);
await page.click('[data-a=ana]'); await page.waitForTimeout(4000);
await page.screenshot({ path: 'shots/31-ana.png', fullPage: true });
console.log('Ana:', await page.textContent('.note'));
await page.evaluate(() => window.__app.home()); await page.waitForTimeout(200);
await page.screenshot({ path: 'shots/32-home.png' });
console.log('Fehler:', errs);
await browser.close();
